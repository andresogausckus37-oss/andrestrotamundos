/* =========================================================
   SELECCIONAR PERSONAJE
========================================================= */

function seleccionarPersonajeLaberinto({
  tema,
  personajeSeleccionado,
  modoPersonaje,
  indice,
  semilla,
}) {
  const personajesTema =
    PERSONAJES_POR_TEMATICA[
      tema
    ] ||
    PERSONAJES_POR_TEMATICA
      .mascotas;

  if (
    personajesTema.length === 0
  ) {
    return "toby";
  }

  const indiceSeguro =
    Math.abs(
      Number.isFinite(indice)
        ? Math.floor(indice)
        : 0
    );

    /* =======================================================
     FIJO
  ======================================================== */

  if (
    modoPersonaje ===
    "fijo"
  ) {
    if (
      personajeSeleccionado !==
        "automatico" &&
      personajesTema.includes(
        personajeSeleccionado
      )
    ) {
      return personajeSeleccionado;
    }

    return personajesTema[0];
  }

  /* =======================================================
     ALEATORIO DETERMINISTA
  ======================================================== */

  if (
    modoPersonaje ===
    "aleatorio"
  ) {
    const semillaSegura =
      Number.isFinite(semilla)
        ? semilla
        : 1;

    const valor =
      Math.sin(
        semillaSegura *
          12.9898 +
        indiceSeguro *
          78.233
      ) *
      43758.5453;

    const fraccion =
      valor -
      Math.floor(valor);

    const indiceAleatorio =
      Math.floor(
        fraccion *
          personajesTema.length
      );

    return personajesTema[
      indiceAleatorio
    ];
  }

  /* =======================================================
     ROTATIVO
  ======================================================== */

  let inicioRotacion = 0;

  if (
    personajeSeleccionado !==
      "automatico" &&
    personajesTema.includes(
      personajeSeleccionado
    )
  ) {
    inicioRotacion =
      personajesTema.indexOf(
        personajeSeleccionado
      );
  }

  return personajesTema[
    (
      inicioRotacion +
      indiceSeguro
    ) %
      personajesTema.length
  ];
}

