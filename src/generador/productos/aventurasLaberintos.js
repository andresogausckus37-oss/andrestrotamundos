export function obtenerAventuraLaberinto(
  indice = 0,
  tema = "mascotas",
  opciones = {}
) {
  const indiceSeguro =
    Math.abs(
      Number.isFinite(indice)
        ? Math.floor(indice)
        : 0
    );

  const {
    personajeSeleccionado =
      "automatico",

    modoPersonaje =
      "rotativo",

    objetivoSeleccionado =
      "automatico",

    modoObjetivo =
      "rotativo",

    semilla = 1,
  } = opciones;

  /* =======================================================
     SELECCIÓN GENERAL DE PERSONAJE
  ======================================================== */

  const personajeId =
    seleccionarPersonajeLaberinto({
      tema,

      personajeSeleccionado,

      modoPersonaje,

      indice:
        indiceSeguro,

      semilla,
    });

  const personaje =
    PERSONAJES_LABERINTOS[
      personajeId
    ];

  /* =======================================================
     SELECCIÓN GENERAL DE OBJETIVO
  ======================================================== */

  const idObjeto =
    seleccionarObjetivoLaberinto({
      tema,

      objetivoSeleccionado,

      modoObjetivo,

      indice:
        indiceSeguro,

      semilla,
    });

  const objeto =
    OBJETOS_LABERINTOS[
      idObjeto
    ];

  const nombreObjeto =
    objeto?.nombre ||
    "objetivo";

  const articuloObjeto =
    objeto?.articulo ||
    "el";

  /* =======================================================
     MASCOTAS
  ======================================================== */

  if (tema === "mascotas") {
    if (
      AVENTURAS_LABERINTOS.length === 0
    ) {
      return null;
    }

    const aventuraBase =
      AVENTURAS_LABERINTOS[
        indiceSeguro %
          AVENTURAS_LABERINTOS.length
      ];

    /*
      Conservamos los textos originales únicamente
      cuando personaje Y objetivo siguen siendo
      exactamente los de la aventura original.
    */

    const mismaAventura =
      personajeId ===
        aventuraBase.personaje &&
      idObjeto ===
        aventuraBase.objeto;

    const textoAventura =
      mismaAventura
        ? {
            titulo:
              aventuraBase.titulo,

            instrucciones:
              aventuraBase.instrucciones,
          }
        : generarTextoAventura({
            indice:
              indiceSeguro,

            personaje:
              personaje.nombre,

            articulo:
              articuloObjeto,

            objeto:
              nombreObjeto,
          });

    return {
      ...aventuraBase,

      personaje:
        personajeId,

      nombrePersonaje:
        personaje.nombre,

      emojiPersonaje:
        personaje.emoji,

      colorPersonaje:
        personaje.color,

      decoracion:
        personaje.decoracion ||
        aventuraBase.decoracion,

      objeto:
        idObjeto,

      emojiObjeto:
        objeto?.emoji ||
        "⭐",

      titulo:
        textoAventura.titulo,

      instrucciones:
        textoAventura.instrucciones,
    };
  }

  /* =======================================================
     OTRAS TEMÁTICAS
  ======================================================== */

  const configuracionTematica =
    TEMATICAS_LABERINTOS[
      tema
    ] ||
    TEMATICAS_LABERINTOS
      .mascotas;

  const textoAventura =
    generarTextoAventura({
      indice:
        indiceSeguro,

      personaje:
        personaje.nombre,

      articulo:
        articuloObjeto,

      objeto:
        nombreObjeto,
    });

  return {
    tema,

    personaje:
      personajeId,

    nombrePersonaje:
      personaje.nombre,

    emojiPersonaje:
      personaje.emoji,

    colorPersonaje:
      personaje.color,

    decoracion:
      configuracionTematica
        .decoracion,

    objeto:
      idObjeto,

    emojiObjeto:
      objeto?.emoji ||
      "⭐",

    titulo:
      textoAventura.titulo,

    instrucciones:
      textoAventura.instrucciones,
  };
}