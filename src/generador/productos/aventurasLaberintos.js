/* =========================================================
   SELECCIONAR PERSONAJE
========================================================= */

function seleccionarPersonajeLaberinto({
  tema,
  personajeSeleccionado,
  modoPersonaje,
  indice,
  semilla,
}) {
  const personajesTema =
    PERSONAJES_POR_TEMATICA[
      tema
    ] ||
    PERSONAJES_POR_TEMATICA
      .mascotas;

  if (
    personajesTema.length === 0
  ) {
    return "toby";
  }

  const indiceSeguro =
    Math.abs(
      Number.isFinite(indice)
        ? Math.floor(indice)
        : 0
    );

    /* =======================================================
     FIJO
  ======================================================== */

  if (
    modoPersonaje ===
    "fijo"
  ) {
    if (
      personajeSeleccionado !==
        "automatico" &&
      personajesTema.includes(
        personajeSeleccionado
      )
    ) {
      return personajeSeleccionado;
    }

    return personajesTema[0];
  }

  /* =======================================================
     ALEATORIO DETERMINISTA
  ======================================================== */

  if (
    modoPersonaje ===
    "aleatorio"
  ) {
    const semillaSegura =
      Number.isFinite(semilla)
        ? semilla
        : 1;

    const valor =
      Math.sin(
        semillaSegura *
          12.9898 +
        indiceSeguro *
          78.233
      ) *
      43758.5453;

    const fraccion =
      valor -
      Math.floor(valor);

    const indiceAleatorio =
      Math.floor(
        fraccion *
          personajesTema.length
      );

    return personajesTema[
      indiceAleatorio
    ];
  }

  /* =======================================================
     ROTATIVO
  ======================================================== */

  let inicioRotacion = 0;

  if (
    personajeSeleccionado !==
      "automatico" &&
    personajesTema.includes(
      personajeSeleccionado
    )
  ) {
    inicioRotacion =
      personajesTema.indexOf(
        personajeSeleccionado
      );
  }

  return personajesTema[
    (
      inicioRotacion +
      indiceSeguro
    ) %
      personajesTema.length
  ];
}

/* =========================================================
   SELECCIONAR OBJETIVO
========================================================= */

function seleccionarObjetivoLaberinto({
  tema,
  personajeId,
  objetivoSeleccionado,
  modoObjetivo,
  indice,
  semilla,
}) {
  const configuracionObjetos =
    OBJETOS_POR_TEMATICA[
      tema
    ] ||
    OBJETOS_POR_TEMATICA
      .mascotas;

  let objetosTema = [];

  /* =======================================================
     OBTENER OBJETOS DISPONIBLES
  ======================================================== */

  // Estructura antigua:
  // ["objeto1", "objeto2", ...]
  if (
    Array.isArray(
      configuracionObjetos
    )
  ) {
    objetosTema =
      configuracionObjetos;
  }

  // Nueva estructura:
  // {
  //   toby: ["hueso", "pelota"],
  //   luna: [...]
  // }
  else if (
    configuracionObjetos &&
    typeof configuracionObjetos ===
      "object"
  ) {
    objetosTema =
      configuracionObjetos[
        personajeId
      ] || [];
  }

  if (
    objetosTema.length === 0
  ) {
    return "pelota";
  }

  const indiceSeguro =
    Math.abs(
      Number.isFinite(indice)
        ? Math.floor(indice)
        : 0
    );

  /* =======================================================
     FIJO
  ======================================================== */

  if (
    modoObjetivo ===
    "fijo"
  ) {
    if (
      objetivoSeleccionado !==
        "automatico" &&
      objetosTema.includes(
        objetivoSeleccionado
      )
    ) {
      return objetivoSeleccionado;
    }

    return objetosTema[0];
  }

  /* =======================================================
     ALEATORIO DETERMINISTA
  ======================================================== */

  if (
    modoObjetivo ===
    "aleatorio"
  ) {
    const semillaSegura =
      Number.isFinite(semilla)
        ? semilla
        : 1;

    const valor =
      Math.sin(
        semillaSegura *
          22.1357 +
        indiceSeguro *
          91.731
      ) *
      43758.5453;

    const fraccion =
      valor -
      Math.floor(valor);

    const indiceAleatorio =
      Math.floor(
        fraccion *
          objetosTema.length
      );

    return objetosTema[
      indiceAleatorio
    ];
  }

  /* =======================================================
     ROTATIVO
  ======================================================== */

  let inicioRotacion = 0;

  if (
    objetivoSeleccionado !==
      "automatico" &&
    objetosTema.includes(
      objetivoSeleccionado
    )
  ) {
    inicioRotacion =
      objetosTema.indexOf(
        objetivoSeleccionado
      );
  }

  return objetosTema[
    (
      inicioRotacion +
      indiceSeguro
    ) %
      objetosTema.length
  ];
}

export function obtenerAventuraLaberinto(
  indice = 0,
  tema = "mascotas",
  opciones = {}
) {
  const indiceSeguro =
    Math.abs(
      Number.isFinite(indice)
        ? Math.floor(indice)
        : 0
    );

  const {
    personajeSeleccionado =
      "automatico",

    modoPersonaje =
      "rotativo",

    objetivoSeleccionado =
      "automatico",

    modoObjetivo =
      "rotativo",

    semilla = 1,
  } = opciones;

  /* =======================================================
     SELECCIÓN GENERAL DE PERSONAJE
  ======================================================== */

  const personajeId =
    seleccionarPersonajeLaberinto({
      tema,

      personajeSeleccionado,

      modoPersonaje,

      indice:
        indiceSeguro,

      semilla,
    });

  const personaje =
    PERSONAJES_LABERINTOS[
      personajeId
    ];

  /* =======================================================
     SELECCIÓN GENERAL DE OBJETIVO
  ======================================================== */

  const idObjeto =
    seleccionarObjetivoLaberinto({
      tema,

      personajeId,

      objetivoSeleccionado,

      modoObjetivo,

      indice:
        indiceSeguro,

      semilla,
    });

  const objeto =
    OBJETOS_LABERINTOS[
      idObjeto
    ];

  const nombreObjeto =
    objeto?.nombre ||
    "objetivo";

  const articuloObjeto =
    objeto?.articulo ||
    "el";

  /* =======================================================
     MASCOTAS
  ======================================================== */

  if (tema === "mascotas") {
    if (
      AVENTURAS_LABERINTOS.length === 0
    ) {
      return null;
    }

    const aventuraBase =
      AVENTURAS_LABERINTOS[
        indiceSeguro %
          AVENTURAS_LABERINTOS.length
      ];

    /*
      Conservamos los textos originales únicamente
      cuando personaje Y objetivo siguen siendo
      exactamente los de la aventura original.
    */

    const mismaAventura =
      personajeId ===
        aventuraBase.personaje &&
      idObjeto ===
        aventuraBase.objeto;

    const textoAventura =
      mismaAventura
        ? {
            titulo:
              aventuraBase.titulo,

            instrucciones:
              aventuraBase.instrucciones,
          }
        : generarTextoAventura({
            indice:
              indiceSeguro,

            personaje:
              personaje.nombre,

            articulo:
              articuloObjeto,

            objeto:
              nombreObjeto,
          });

    return {
      ...aventuraBase,

      personaje:
        personajeId,

      nombrePersonaje:
        personaje.nombre,

      emojiPersonaje:
        personaje.emoji,

      colorPersonaje:
        personaje.color,

      decoracion:
        personaje.decoracion ||
        aventuraBase.decoracion,

      objeto:
        idObjeto,

      emojiObjeto:
        objeto?.emoji ||
        "⭐",

      titulo:
        textoAventura.titulo,

      instrucciones:
        textoAventura.instrucciones,
    };
  }

  /* =======================================================
     OTRAS TEMÁTICAS
  ======================================================== */

  const configuracionTematica =
    TEMATICAS_LABERINTOS[
      tema
    ] ||
    TEMATICAS_LABERINTOS
      .mascotas;

  const textoAventura =
    generarTextoAventura({
      indice:
        indiceSeguro,

      personaje:
        personaje.nombre,

      articulo:
        articuloObjeto,

      objeto:
        nombreObjeto,
    });

  return {
    tema,

    personaje:
      personajeId,

    nombrePersonaje:
      personaje.nombre,

    emojiPersonaje:
      personaje.emoji,

    colorPersonaje:
      personaje.color,

    decoracion:
      configuracionTematica
        .decoracion,

    objeto:
      idObjeto,

    emojiObjeto:
      objeto?.emoji ||
      "⭐",

    titulo:
      textoAventura.titulo,

    instrucciones:
      textoAventura.instrucciones,
  };
}